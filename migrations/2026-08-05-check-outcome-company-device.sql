-- ① ຜົນກວດເຊັກ — 'cannot_repair' | 'replace_advice' (null = ງານສ້ອມປົກກະຕິ)
alter table tb_product add column if not exists check_outcome varchar(20);

comment on column tb_product.check_outcome is
  'ຜົນກວດເຊັກທີ່ຈົບໂດຍບໍ່ສ້ອມ: cannot_repair=ສ້ອມບໍ່ໄດ້ · replace_advice=ແນະນຳປ່ຽນເຄື່ອງ(ສົ່ງຕໍ່ຝ່າຍຂາຍ) · null=ງານປົກກະຕິ. ນິຍາມຢູ່ src/lib/check-outcome.ts';

-- ② ໃບເຄື່ອງບໍລິສັດ ຊີ້ກັບໄປໃບເດີມຂອງລູກຄ້າ (ທາງດຽວພໍ — ຫາທາງກັບດ້ວຍ where)
alter table tb_product add column if not exists company_from_job varchar(20);

comment on column tb_product.company_from_job is
  'ໃບນີ້ຮັບເຂົ້າເປັນເຄື່ອງບໍລິສັດ ຈາກໃບສ້ອມເລກນີ້ (ຫຼັງແນະນຳໃຫ້ລູກຄ້າປ່ຽນເຄື່ອງ) — null = ໃບປົກກະຕິ';

-- ຄິວ "ແນະນຳປ່ຽນເຄື່ອງ ທີ່ຍັງບໍ່ໄດ້ຮັບເຂົ້າ" ຖາມແຖວກຸ່ມນີ້ ⇒ index ສະເພາະແຖວທີ່ມີຄ່າ
create index if not exists tb_product_check_outcome_idx
  on tb_product (check_outcome, time_finish_check desc)
  where check_outcome is not null;

-- ຫາ "ໃບເດີມນີ້ ຮັບເຂົ້າເປັນເຄື່ອງບໍລິສັດແລ້ວບໍ" ⇒ ດ່ານກັນຮັບຊ້ຳ ຕ້ອງໄວ
create index if not exists tb_product_company_from_job_idx
  on tb_product (company_from_job)
  where company_from_job is not null;

