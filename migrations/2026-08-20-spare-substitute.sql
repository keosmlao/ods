create table if not exists ods.spare_sub_group (
  group_id serial primary key,
  -- ຊື່ກຸ່ມທີ່ຄົນອ່ານ ເຊັ່ນ "ທໍ່ PVC ສີເຫຼືອງ 3/8 (1ມັດ=50 ເສັ້ນ)"
  name_1   varchar(255) not null default '',
  create_date_time_now timestamp default localtimestamp(0)
);

comment on table ods.spare_sub_group is
  'ກຸ່ມອາໄຫຼ່ທີ່ໃຊ້ທົດແທນກັນໄດ້ (spec ດຽວກັນ ຕ່າງຍີ່ຫໍ້) — ໃຊ້ຮ່ວມທຸກໝວດຊຸດ';

create table if not exists ods.spare_sub_item (
  group_id int not null
    references ods.spare_sub_group(group_id) on update cascade on delete cascade,
