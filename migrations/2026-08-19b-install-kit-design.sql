create table if not exists ods.install_kit_design (
  install_type varchar(25) not null
    references ods.install_kit_type(install_type) on update cascade on delete cascade,
  -- `ic_design.code` ຂອງ ERP (ແອຕິດຝາ=120101 · ແອແຄັດເສັດ=120203 …)
  ic_design    varchar(25) not null,
  create_date_time_now timestamp default localtimestamp(0),
  -- ຮູບແບບດຽວກັນໃສ່ໝວດດຽວສອງເທື່ອບໍ່ໄດ້
  primary key (install_type, ic_design)
);

comment on table ods.install_kit_design is
  'ຮູບແບບ (ic_design) ທີ່ແຕ່ລະໝວດຊຸດອາໄຫຼ່ຄຸມ — 1 install_type ມີໄດ້ຫຼາຍ ic_design';

-- ຫາວ່າ "ຮູບແບບນີ້ຖືກໝວດໃດຈອງແລ້ວ" (ດ່ານກັນຊ້ຳຢູ່ actions/install-kit)
create index if not exists idx_install_kit_design_design
  on ods.install_kit_design (ic_design);

